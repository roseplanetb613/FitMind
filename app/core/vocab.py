# "我最近练了什么"要留在记忆域回读打卡，不能被这里截胡（见 is_profile_query 的否决门）。
_PROF_DOMAIN_KW = ("档案", "资料", "信息", "身体", "身高", "体重", "年龄", "岁",
                   "目标", "活动系数", "性别", "称呼", "名字",
                   "基础代谢", "bmr", "体脂", "肌肉量", "腰臀比", "柔韧性",
                   "训练年限", "骨量", "握力")
# 记录型否决：属记忆域（回读打卡/饮食），不是档案
_PROF_RECORD_KW = ("练了", "练过", "吃了", "喝过", "打卡", "训练记录",
                   "训练日志", "受伤记录")

# 档案字段的**变更动词**（单源）。此前只有 `_WEIGHT_STMT_RE` 把「改成|改为」写成
# 字面量，于是体重能改、目标/身高不能改（实测"把目标改成减脂"抽不出来 →
# 图谱没变、答"当前计划里没有「目标」这个动作"）。集中此处，三个字段正则共读。
PROFILE_CHANGE_V = ("改成", "改为", "改到", "设成", "设为", "变成", "换成",
                    "换为", "调成", "调为", "设置成", "设置为")

# **可改的**档案字段名词（不是全部档案词）：用于"这是改档案还是改计划"的否决。
# 与 `_PROF_DOMAIN_KW` 分开：那个还含"档案/资料/信息/身体"等泛词，拿来做否决
# 会把"把目标肌群换成胸"这种也拦下来。这里只要字段本身。
_PROFILE_FIELD_KW = ("目标", "体重", "身高", "年龄", "活动系数", "性别", "称呼")


def is_profile_field_word(text: str) -> bool:
    """句中是否出现**可改的档案字段名**（plan_edit 的否决门用）。"""
    return any(k in (text or "") for k in _PROFILE_FIELD_KW)


def is_profile_query(text: str) -> bool:
    """用户**自己的档案**查询（身高/体重/年龄/目标/活动系数…）——从严判定。

    放在 vocab（而不是 router）是因为 **llm.classify 也要读它**：概念规则
    「X是什么」conf=1.0 且跑在 _RULES 循环之前，会把"我的目标是什么"截胡成
    通识题（实测）。llm 不能 import router（router 已 import llm，会成环），
    而两边都 import vocab 是既有格局。

    四门全过才算：自指 + 档案域名词 + **非记录型** + **非建议型**。
    后两门是否决门，防同一句式在别的语境下被误抢：
        我最近练了什么 → 记录型 → 记忆域（回读打卡），不在这里截胡
        我的体重怎么减 → 建议型 → 该走咨询，不是读档案
    """
    t = text or ""
    if any(k in t for k in _PROF_RECORD_KW):
        return False                       # 记录回读属记忆域
    if any(k in t for k in _MEM_ADVICE_KW):
        return False                       # 建议/教学型不碰
    if not any(k in t for k in _PROF_SELF_KW):
        return False
    return any(k in t for k in _PROF_DOMAIN_KW)


