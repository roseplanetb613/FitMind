// Build translations
const result = {};
let untranslated = [];

for (const name of names) {
  // Check hardcoded first
  if (hardcoded[name]) {
    result[name] = hardcoded[name];
    continue;
  }

  const lower = name.toLowerCase();

  // Try exact match
  if (terms[lower]) {
    result[name] = terms[lower];
    continue;
  }

  // Build translation piece by piece using longest-match-first
  let zh = name;
  const sorted = Object.entries(terms).sort((a, b) => b[0].length - a[0].length);

  for (const [en, zh_term] of sorted) {
    const escaped = en.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const regex = new RegExp(escaped, 'gi');
    zh = zh.replace(regex, zh_term);
  }

  // Clean up extra spaces and repeated terms
  zh = zh.replace(/\s+/g, ' ').trim();

  result[name] = zh;

  // Check if still contains Latin chars (untranslated parts)
  if (/[a-zA-Z]{3,}/.test(zh.replace(/[A-Z\s]/g, '')) || /[a-zA-Z]{2,}/.test(zh)) {
    untranslated.push({ en: name, zh: zh });
  }
}

fs.writeFileSync('data/name_zh.json', JSON.stringify(result, null, 2));
